def translate(key: str, lang: str = DEFAULT_LANG) -> str:
    """Кілт бойынша аударма. Табылмаса — қазақшасы, ол да болмаса — кілттің өзі."""
    lang = lang if lang in LANGUAGES else DEFAULT_LANG
    return TRANSLATIONS[lang].get(key) or TRANSLATIONS[DEFAULT_LANG].get(key) or key


def missing_keys() -> dict[str, set[str]]:
    """Тесттер үшін: қай тілде қандай кілттер жетіспейтінін қайтарады."""
    all_keys = set().union(*(d.keys() for d in TRANSLATIONS.values()))
    return {lang: all_keys - set(d.keys()) for lang, d in TRANSLATIONS.items()}
